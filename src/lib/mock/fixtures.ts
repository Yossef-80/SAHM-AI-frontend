export const performance = (seed: number): MetricPoint[] =>
  Array.from({ length: 14 }, (_, i) => {
    const d = new Date(Date.now() - (13 - i) * 86_400_000);
    const wave = 1 + 0.25 * Math.sin((i + seed) / 2);
    return {
      date: d.toISOString().slice(0, 10),
      impressions: Math.round(28_000 * wave),
      clicks: Math.round(620 * wave),
      conversions: Math.round(15 * wave),
      spend: Math.round(1_300 * wave),
    };
  });

